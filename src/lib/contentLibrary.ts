export const getRandomText = (theme: Theme, category: 'opening' | 'middle' | 'closing'): string => {
  const options = contentLibrary[theme][category];
  return options[Math.floor(Math.random() * options.length)];
};

export const generateSceneTexts = (theme: Theme, sceneCount: number): string[] => {
  const texts: string[] = [];

  // Add opening hook
  texts.push(getRandomText(theme, 'opening'));

  // Add middle value lines
  const middleCount = Math.max(1, sceneCount - 2);
  for (let i = 0; i < middleCount; i++) {
    texts.push(getRandomText(theme, 'middle'));
  }

  // Add closing CTA
  texts.push(getRandomText(theme, 'closing'));

  return texts.slice(0, sceneCount);
};
